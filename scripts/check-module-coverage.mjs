const rowPattern = /^\s*#\s+([^|]+\.ts)\s+\|\s+([0-9.]+)\s+\|/gm;
for (const match of result.stdout.matchAll(rowPattern)) {
  const lines = Number(match[2]);
  if (Number.isFinite(lines) && lines < 90) {
    belowModuleThreshold.push(`${match[1].trim()} (${lines.toFixed(2)}%)`);
  }
}
if (belowModuleThreshold.length > 0) {
  console.error("Per-module line coverage is below 90%:");
  for (const module of belowModuleThreshold) console.error(`- ${module}`);
  process.exit(1);
}
